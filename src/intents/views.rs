//! Generated `TODO.md` and `DONE.md` (INT-6), rewritten on every Towercab write.

use std::sync::LazyLock;

use regex::Regex;

use super::id::sort_key;
use super::intent::Intent;
use super::store::Listing;
use crate::priority::{self, parked, priority};

/// Start of the line that marks a generated view (INT-13's run-once guard).
pub const MARKER: &str = "<!-- generated by towercab";

static PR: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"^https://github\.com/[^/\s]+/([^/\s]+)/pull/(\d+)/?$").unwrap());

/// True when some line starts with [`MARKER`].
pub fn is_generated(text: &str) -> bool {
    text.lines().any(|l| l.starts_with(MARKER))
}

/// `[<repo>#<n>](<url>)` for a GitHub PR URL, else the value.
pub fn pr_link(pr: &str) -> String {
    match PR.captures(pr) {
        Some(c) => format!("[{}#{}]({pr})", &c[1], &c[2]),
        None => pr.to_string(),
    }
}

/// `<m>m<ss>s` under an hour, else `<h>h<mm>m`.
pub fn agent_time(secs: u64) -> String {
    if secs < 3600 {
        format!("{}m{:02}s", secs / 60, secs % 60)
    } else {
        format!("{}h{:02}m", secs / 3600, (secs % 3600) / 60)
    }
}

/// A value on one line: every run of whitespace (line breaks included) → one space, so a
/// value can't start a heading or an entry of its own in a view.
pub fn one_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn head(i: &Intent) -> String {
    format!(
        "- [{}]({}/intent.md) {}: {}",
        i.id,
        i.dir,
        one_line(i.repo()),
        one_line(i.title())
    )
}

fn with_pr(i: &Intent) -> String {
    i.pr()
        .map(|p| format!(" · {}", pr_link(&one_line(p))))
        .unwrap_or_default()
}

fn section(out: &mut String, title: &str, lines: &[String]) {
    if !lines.is_empty() {
        out.push_str(&format!("\n## {title}\n\n{}\n", lines.join("\n")));
    }
}

/// `TODO.md`: Waiting on me, In flight, Next, Parked (`priority < cutoff`), Can't read.
pub fn todo(listing: &Listing, cutoff: u8) -> String {
    let finished = listing.finished_ids();
    let mut open: Vec<&Intent> = listing
        .open
        .iter()
        .filter(|i| !i.stage().is_some_and(|s| s.is_finished()))
        .collect();
    open.sort_by(|a, b| priority::cmp(a, b));
    let (mut waiting, mut flight, mut next, mut later) = (vec![], vec![], vec![], vec![]);
    for i in open {
        if let Some(w) = i.waiting() {
            waiting.push(format!("{} · **{}**{}", head(i), one_line(w), with_pr(i)));
        } else if let Some(stage) = i.stage() {
            flight.push(format!("{} · {stage}{}", head(i), with_pr(i)));
        } else {
            let p = priority(i.u(), i.i());
            let mut line = format!(
                "{} · p{p} u{} i{}",
                head(i),
                i.u().unwrap_or(priority::DEFAULT_SCORE),
                i.i().unwrap_or(priority::DEFAULT_SCORE)
            );
            if let Some(a) = i.a() {
                line.push_str(&format!(" a{a}"));
            }
            let unfinished: Vec<&str> = i
                .after()
                .iter()
                .filter(|id| !finished.contains(*id))
                .map(String::as_str)
                .collect();
            if !unfinished.is_empty() {
                line.push_str(&format!(" · after {}", unfinished.join(", ")));
            }
            if parked(p, cutoff) {
                later.push(line);
            } else {
                next.push(line);
            }
        }
    }
    let mut bad: Vec<_> = listing.unreadable.iter().collect();
    bad.sort_by(|a, b| a.path.cmp(&b.path));
    let bad: Vec<String> = bad
        .iter()
        .map(|u| format!("- {}: {}", one_line(&u.path), one_line(&u.reason)))
        .collect();
    let mut out =
        format!("# TODO\n\n{MARKER} from intents/*/intent.md: edit those, not this file -->\n");
    if [&waiting, &flight, &next, &later, &bad]
        .iter()
        .all(|s| s.is_empty())
    {
        out.push_str("\nNothing open.\n");
        return out;
    }
    section(&mut out, "Waiting on me", &waiting);
    section(&mut out, "In flight", &flight);
    section(&mut out, "Next", &next);
    section(&mut out, "Parked", &later);
    section(&mut out, "Can't read", &bad);
    out
}

/// `YYYY-MM-DD` of `finished`, else of the ID.
pub fn done_date(i: &Intent) -> String {
    match i.finished() {
        Some(t) => t.format("%Y-%m-%d").to_string(),
        None => {
            let (ymd, _, _) = sort_key(&i.id);
            format!(
                "20{:02}-{:02}-{:02}",
                ymd / 10000,
                ymd / 100 % 100,
                ymd % 100
            )
        }
    }
}

/// `DONE.md`: finished intents newest first, then `done/legacy.md` verbatim.
pub fn done(listing: &Listing) -> String {
    let mut done: Vec<(String, &Intent)> = listing.done.iter().map(|i| (done_date(i), i)).collect();
    done.sort_by(|(da, a), (db, b)| {
        db.cmp(da)
            .then_with(|| sort_key(&b.id).cmp(&sort_key(&a.id)))
    });
    let lines: Vec<String> = done
        .iter()
        .map(|(date, i)| {
            let head = head(i).replacen("- ", &format!("- {date} "), 1);
            if i.stage() == Some(super::Stage::Dropped) {
                return format!("{head} · dropped{}", with_pr(i));
            }
            let opt = |v: Option<String>| v.unwrap_or_else(|| "?".into());
            format!(
                "{head} · {} · ${} · {} · {}",
                i.pr()
                    .map_or_else(|| "no PR".into(), |p| pr_link(&one_line(p))),
                opt(i.cost().map(|c| format!("{c:.2}"))),
                opt(i.agent_time().map(agent_time)),
                opt(i.attempts().map(|n| n.to_string())),
            )
        })
        .collect();
    let legacy = listing.legacy.trim_end_matches(['\n', '\r']);
    let mut out = format!(
        "# DONE\n\n{MARKER} from done/*/intent.md and done/legacy.md: edit those, not this file -->\n"
    );
    if lines.is_empty() && legacy.trim().is_empty() {
        out.push_str("\nNothing done.\n");
        return out;
    }
    if !lines.is_empty() {
        out.push_str(&format!("\n{}\n", lines.join("\n")));
    }
    if !legacy.trim().is_empty() {
        out.push_str(&format!("\n## Before intents\n\n{legacy}\n"));
    }
    out
}

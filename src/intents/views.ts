// The generated `TODO.md` and `DONE.md` (INT-6, PRI-6), rewritten on every Towercab write.

import { cmpIntents, DEFAULT_SCORE, isParked, priorityOf } from "../priority.ts";
import { cmpIds } from "./id.ts";
import { oneLine } from "./intent.ts";
import type { Intent, Listing } from "./types.ts";

/** Start of the line that marks a generated view. */
export const MARKER = "<!-- generated by towercab";

const PR = /^https:\/\/github\.com\/[^/\s]+\/([^/\s]+)\/pull\/(\d+)\/?$/;

/** Some line starts with `MARKER`. */
export function isGenerated(text: string): boolean {
  return text.split("\n").some((l) => l.startsWith(MARKER));
}

/** `[<repo>#<n>](<url>)` for a GitHub PR URL, else the value. */
export function prLink(pr: string): string {
  const m = PR.exec(pr);
  return m ? `[${m[1]}#${m[2]}](${pr})` : pr;
}

/** `<m>m<ss>s` under an hour, else `<h>h<mm>m`. */
export function agentTime(secs: number): string {
  const p = (n: number) => String(n).padStart(2, "0");
  if (secs < 3600) return `${Math.floor(secs / 60)}m${p(secs % 60)}s`;
  return `${Math.floor(secs / 3600)}h${p(Math.floor((secs % 3600) / 60))}m`;
}

/** The newest PR an intent has: the code PR, else the plan PR, else the spec PR. */
export function latestPr(i: Intent): string | null {
  return i.pr ?? i.planPr ?? i.specPr;
}

const head = (i: Intent) => `- [${i.id}](${i.dir}/intent.md) ${oneLine(i.repo)}: ${oneLine(i.title)}`;

function withPr(pr: string | null): string {
  return pr === null ? "" : ` · ${prLink(oneLine(pr))}`;
}

function section(title: string, lines: string[]): string {
  return lines.length ? `\n## ${title}\n\n${lines.join("\n")}\n` : "";
}

/** `TODO.md`: Waiting on me, In flight, Next, Parked (below `cutoff`), Can't read. */
export function todoView(listing: Listing, cutoff: number): string {
  const waiting: string[] = [];
  const flight: string[] = [];
  const next: string[] = [];
  const parked: string[] = [];
  const open = listing.open.filter((i) => i.stage !== "done" && i.stage !== "dropped").sort(cmpIntents);
  for (const i of open) {
    if (i.waiting !== null) {
      // UI-163: the owner's steps say how many are left.
      const left = i.stepsLeft ? ` · ${oneLine(i.stepsLeft)} left` : "";
      waiting.push(`${head(i)} · **${oneLine(i.waiting)}**${left}${withPr(latestPr(i))}`);
    } else if (i.stage !== null) flight.push(`${head(i)} · ${i.stage}${withPr(latestPr(i))}`);
    else {
      let line = `${head(i)} · p${priorityOf(i)} u${i.u ?? DEFAULT_SCORE} i${i.i ?? DEFAULT_SCORE}`;
      if (i.a !== null) line += ` a${i.a}`;
      const notDone = i.after.filter((a) => !listing.doneIds.has(a));
      if (notDone.length) line += ` · after ${notDone.join(", ")}`;
      (isParked(i, cutoff) ? parked : next).push(line);
    }
  }
  const bad = [...listing.unreadable]
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0))
    .map((u) => `- ${oneLine(u.path)}: ${oneLine(u.reason)}`);
  let out = `# TODO\n\n${MARKER} from intents/*/intent.md: edit those, not this file -->\n`;
  if ([waiting, flight, next, parked, bad].every((s) => s.length === 0)) return `${out}\nNothing open.\n`;
  out += section("Waiting on me", waiting);
  out += section("In flight", flight);
  out += section("Next", next);
  out += section("Parked", parked);
  out += section("Can't read", bad);
  return out;
}

/** `YYYY-MM-DD` of `finished` (as written), else of the ID. */
export function doneDate(i: Intent): string {
  if (i.finished) return i.finished.slice(0, 10);
  return `20${i.id.slice(0, 2)}-${i.id.slice(2, 4)}-${i.id.slice(4, 6)}`;
}

/** `DONE.md`: finished intents newest first, then `done/legacy.md` verbatim under `## Before intents`. */
export function doneView(listing: Listing, legacy: string): string {
  const done = listing.done
    .map((i) => ({ date: doneDate(i), i }))
    .sort((a, b) => (a.date !== b.date ? (a.date < b.date ? 1 : -1) : cmpIds(b.i.id, a.i.id)));
  const lines = done.map(({ date, i }) => {
    const h = head(i).replace("- ", `- ${date} `);
    if (i.stage === "dropped") return `${h} · dropped${withPr(latestPr(i))}`;
    const opt = (v: string | null) => v ?? "?";
    // SHIP-21, UI-163: merged but never checked live.
    const unverified = i.verified === "no" ? " (merged, not verified live)" : "";
    return (
      `${h}${unverified} · ${i.pr === null ? "no PR" : prLink(oneLine(i.pr))}` +
      ` · $${opt(i.cost === null ? null : i.cost.toFixed(2))}` +
      ` · ${opt(i.agentTime === null ? null : agentTime(i.agentTime))}` +
      ` · ${opt(i.attempts === null ? null : String(i.attempts))}`
    );
  });
  const old = legacy.replace(/[\r\n]+$/, "");
  let out = `# DONE\n\n${MARKER} from done/*/intent.md and done/legacy.md: edit those, not this file -->\n`;
  if (!lines.length && !old.trim()) return `${out}\nNothing done.\n`;
  if (lines.length) out += `\n${lines.join("\n")}\n`;
  if (old.trim()) out += `\n## Before intents\n\n${old}\n`;
  return out;
}

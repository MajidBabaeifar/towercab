//! Generated TODO.md and DONE.md (INT-6), priority order (PRI-2..5, minimal).

mod common;

use common::{intent, intent_md};
use towercab::intents::views::{agent_time, done, is_generated, pr_link, todo};
use towercab::intents::{Listing, Unreadable};
use towercab::priority::{parked, priority};

const PR21: &str = "https://github.com/MajidBabaeifar/towercab/pull/21";

#[test]
fn test_todo_view() {
    assert_eq!(priority(Some(4), Some(5)), 14);
    assert_eq!(priority(None, None), 9, "missing scores count as 3");
    assert!(parked(6, 7) && !parked(7, 7));

    let open =
        |dir: &str, extra: &str, title: &str| intent(dir, &intent_md("towercab", extra, title));
    let listing = Listing {
        open: vec![
            open("intents/261020-0722-c", "", "No scores"),
            open("intents/261019-1000-d", "u: 1\ni: 1\n", "Parked low"),
            open("intents/261020-0721-a", "u: 4\ni: 5\na: 5\n", "Top"),
            open("intents/261019-0800-older", "u: 4\ni: 5\n", "Older top"),
            open(
                "intents/261020-0721-2-b",
                "u: 3\ni: 4\nafter: [261020-0721, 261015-1446, 261014-0900]\n",
                "Waits for others",
            ),
            open("intents/261019-1100-e", "u: 2\ni: 2\n", "Parked six"),
            open(
                "intents/261018-0900-w",
                &format!("u: 1\ni: 1\nstage: deploy\nwaiting: review and merge PR\npr: {PR21}\n"),
                "Needs me",
            ),
            open("intents/261018-1000-f", "stage: build\n", "Building"),
            open(
                "intents/261018-1100-g",
                "u: 5\ni: 5\nstage: test\npr: https://example.com/x\n",
                "Testing",
            ),
        ],
        done: vec![intent(
            "done/261014-0900-old",
            &intent_md("towercab", "stage: done\n", "Old"),
        )],
        unreadable: vec![
            Unreadable {
                path: "intents/zzz".into(),
                reason: "not an <id>-<slug> folder".into(),
            },
            Unreadable {
                path: "intents/261017-0000-x/intent.md".into(),
                reason: "u must be an integer 1-5".into(),
            },
        ],
        legacy: "2026-10-15 261015-1446 towercab: Rename · towercab#5 · $3.59 · 1m26s · 1\n".into(),
    };
    let want = "# TODO

<!-- generated by towercab from intents/*/intent.md: edit those, not this file -->

## Waiting on me

- [261018-0900](intents/261018-0900-w/intent.md) towercab: Needs me · **review and merge PR** · [towercab#21](https://github.com/MajidBabaeifar/towercab/pull/21)

## In flight

- [261018-1100](intents/261018-1100-g/intent.md) towercab: Testing · test · https://example.com/x
- [261018-1000](intents/261018-1000-f/intent.md) towercab: Building · build

## Next

- [261019-0800](intents/261019-0800-older/intent.md) towercab: Older top · p14 u4 i5
- [261020-0721](intents/261020-0721-a/intent.md) towercab: Top · p14 u4 i5 a5
- [261020-0721-2](intents/261020-0721-2-b/intent.md) towercab: Waits for others · p11 u3 i4 · after 261020-0721
- [261020-0722](intents/261020-0722-c/intent.md) towercab: No scores · p9 u3 i3

## Parked

- [261019-1100](intents/261019-1100-e/intent.md) towercab: Parked six · p6 u2 i2
- [261019-1000](intents/261019-1000-d/intent.md) towercab: Parked low · p3 u1 i1

## Can't read

- intents/261017-0000-x/intent.md: u must be an integer 1-5
- intents/zzz: not an <id>-<slug> folder
";
    assert_eq!(todo(&listing, 7), want);
    assert!(is_generated(want));
    // The cutoff comes from config: at 4 only p3 is parked.
    assert!(todo(&listing, 4).contains("## Parked\n\n- [261019-1000](intents/261019-1000-d/intent.md) towercab: Parked low · p3 u1 i1\n\n## Can't read"));
    // Empty sections are left out; nothing at all → "Nothing open."
    assert_eq!(
        todo(&Listing::default(), 7),
        "# TODO\n\n<!-- generated by towercab from intents/*/intent.md: edit those, not this file -->\n\nNothing open.\n"
    );
    // Values are put on one line: a line break in one can't start a heading or an entry.
    let multi = Listing {
        open: vec![open(
            "intents/261020-0721-a",
            "waiting: \"line one\\n## Injected\\n- [x] fake\"\npr: \"https://x\\n# y\"\n",
            "Multi",
        )],
        unreadable: vec![Unreadable {
            path: "intents/a\nb".into(),
            reason: "two\nlines".into(),
        }],
        ..Listing::default()
    };
    assert!(todo(&multi, 7).ends_with(
        "## Waiting on me\n\n- [261020-0721](intents/261020-0721-a/intent.md) towercab: Multi · **line one ## Injected - [x] fake** · https://x # y\n\n## Can't read\n\n- intents/a b: two lines\n"
    ));
    let only_next = Listing {
        open: vec![open("intents/261020-0721-a", "", "Only")],
        ..Listing::default()
    };
    assert!(todo(&only_next, 7).ends_with("-->\n\n## Next\n\n- [261020-0721](intents/261020-0721-a/intent.md) towercab: Only · p9 u3 i3\n"));
    assert!(!is_generated(
        "# TODO\n\n- [ ] 261020-0721 towercab: old line\n"
    ));
}

#[test]
fn test_done_view() {
    assert_eq!(agent_time(86), "1m26s");
    assert_eq!(agent_time(5), "0m05s");
    assert_eq!(agent_time(3599), "59m59s");
    assert_eq!(agent_time(3700), "1h01m");
    assert_eq!(pr_link(PR21), format!("[towercab#21]({PR21})"));
    assert_eq!(pr_link("https://example.com/7"), "https://example.com/7");

    let fin =
        |dir: &str, extra: &str, title: &str| intent(dir, &intent_md("towercab", extra, title));
    let listing = Listing {
        done: vec![
            fin("done/261015-0900-z", "", "Moved by hand"),
            fin(
                "done/261016-0403-3-x",
                &format!(
                    "stage: done\npr: {PR21}\ncost: 3.5\nagent_time: 86\nattempts: 1\nfinished: 2026-10-18T09:00:00+02:00\n"
                ),
                "Publish early",
            ),
            fin(
                "done/261017-0900-y",
                "stage: dropped\nfinished: 2026-10-18T08:00:00+02:00\n",
                "Not needed",
            ),
            fin(
                "intents/261017-1000-h",
                &format!("stage: dropped\npr: {PR21}\nfinished: 2026-10-18T23:30:00-05:00\n"),
                "Dropped in place",
            ),
            fin(
                "done/261016-1000-long",
                "stage: done\nagent_time: 3700\ncost: 12\nattempts: 3\n",
                "Long one",
            ),
        ],
        legacy: "2026-10-15 261015-1446 towercab: Rename · towercab#5 · $3.59 · 1m26s · 1\n\
2026-10-15 261015-1715 towercab: Dropped thing · dropped\n\n"
            .into(),
        ..Listing::default()
    };
    let want = "# DONE

<!-- generated by towercab from done/*/intent.md and done/legacy.md: edit those, not this file -->

- 2026-10-18 [261017-1000](intents/261017-1000-h/intent.md) towercab: Dropped in place · dropped · [towercab#21](https://github.com/MajidBabaeifar/towercab/pull/21)
- 2026-10-18 [261017-0900](done/261017-0900-y/intent.md) towercab: Not needed · dropped
- 2026-10-18 [261016-0403-3](done/261016-0403-3-x/intent.md) towercab: Publish early · [towercab#21](https://github.com/MajidBabaeifar/towercab/pull/21) · $3.50 · 1m26s · 1
- 2026-10-16 [261016-1000](done/261016-1000-long/intent.md) towercab: Long one · no PR · $12.00 · 1h01m · 3
- 2026-10-15 [261015-0900](done/261015-0900-z/intent.md) towercab: Moved by hand · no PR · $? · ? · ?

## Before intents

2026-10-15 261015-1446 towercab: Rename · towercab#5 · $3.59 · 1m26s · 1
2026-10-15 261015-1715 towercab: Dropped thing · dropped
";
    assert_eq!(done(&listing), want);
    assert!(is_generated(want));
    assert_eq!(
        done(&Listing::default()),
        "# DONE\n\n<!-- generated by towercab from done/*/intent.md and done/legacy.md: edit those, not this file -->\n\nNothing done.\n"
    );
    let legacy_only = Listing {
        legacy: "2026-10-15 261015-1446 towercab: Rename\n".into(),
        ..Listing::default()
    };
    assert!(
        done(&legacy_only)
            .ends_with("-->\n\n## Before intents\n\n2026-10-15 261015-1446 towercab: Rename\n")
    );
}

//! `towercab migrate` (INT-13).

mod common;

use common::{Home, intent_md, t};
use towercab::intents::migrate::{legacy_lines, migrate, parse_line};
use towercab::intents::store::OLD_FORMAT;
use towercab::intents::{NewIntent, StoreError};

const TODO: &str = "# TODO

## towercab

- [!] 261016-0403-3 u3 i3 a5 towercab: Publish early + CI loop (PIP-2, PIP-3) after:261016-0403-2 @opus
  done when: local verify no longer gates
  pr: https://github.com/MajidBabaeifar/towercab/pull/21
  note: review PR
- [ ] u4 i5 towercab: Thing without an id review:fable
- [~] 261017-1200 towercab: Running one
  owner: majid
- [x] 261017-1300 a2 pocket-notes: Finished one
- [ ] 261017-1400 towercab: Has notes: a file
  done when: it works
  done when: it is fast
  why: because
";

const DONE: &str = "# DONE

<!-- Towercab appends: date id repo: title · PR · cost · agent time · attempts -->
2026-10-15 261015-1446 towercab: Rename · towercab#5 · $3.59 · 1m26s · 1

2026-10-15 261015-1715 towercab: Dropped thing · dropped
";

fn new_intent() -> NewIntent {
    NewIntent {
        repo: "towercab".into(),
        title: "After migrate".into(),
        u: None,
        i: None,
        a: None,
        source: "me".into(),
        created: t("2026-10-21T10:00:00+02:00"),
    }
}

#[test]
fn test_migrate() {
    let hand = intent_md("towercab", "u: 4\ni: 5\n", "Rust crate");
    let home = Home::new(&[
        ("TODO.md", TODO),
        ("DONE.md", DONE),
        ("tasks/261017-1400.md", "Plan:\n- step one\n\n"),
        ("tasks/261099-0000.md", "no task line: left alone\n"),
        ("intents/261020-0721-rust-crate/intent.md", &hand),
    ]);
    let store = home.store();
    assert_eq!(
        store.add(new_intent()).unwrap_err(),
        StoreError::Refused(OLD_FORMAT.into())
    );
    let head = home.head();

    let summary = migrate(&store, t("2026-10-21T09:05:00+02:00")).unwrap();
    assert_eq!(
        summary,
        "migrated 5 intents (1 done), 2 lines to done/legacy.md"
    );
    assert_eq!(home.log()[0], "towercab: migrate 5 intents");
    assert_eq!(home.log()[1], "seed", "one commit");
    assert_eq!(git_parent(&home), head);

    assert_eq!(
        home.remote_file("intents/261016-0403-3-publish-early-ci-loop-pip-2-pip-3/intent.md"),
        "---
repo: towercab
u: 3
i: 3
a: 5
after: [261016-0403-2]
model: opus
source: me
pr: https://github.com/MajidBabaeifar/towercab/pull/21
waiting: review PR
---

# Intent: Publish early + CI loop (PIP-2, PIP-3)

## Proposed outcome

- local verify no longer gates
"
    );
    // No ID → a new one from `now`; only the scores written on the line.
    assert_eq!(
        home.remote_file("intents/261021-0905-thing-without-an-id/intent.md"),
        "---\nrepo: towercab\nu: 4\ni: 5\nreview: fable\nsource: me\n---\n\n# Intent: Thing without an id\n"
    );
    assert_eq!(
        home.remote_file("intents/261017-1200-running-one/intent.md"),
        "---\nrepo: towercab\nsource: me\nwaiting: was running before migrate\n---\n\n\
# Intent: Running one\n\n## Notes\n\n- owner: majid\n"
    );
    assert_eq!(
        home.remote_file("done/261017-1300-finished-one/intent.md"),
        "---\nrepo: pocket-notes\na: 2\nsource: me\nstage: done\n---\n\n# Intent: Finished one\n"
    );
    assert_eq!(
        home.remote_file("intents/261017-1400-has-notes-a-file/intent.md"),
        "---\nrepo: towercab\nsource: me\n---\n\n# Intent: Has notes: a file\n\n\
## Proposed outcome\n\n- it works\n- it is fast\n\n## Notes\n\n- why: because\n\nPlan:\n- step one\n"
    );
    assert!(
        !home.remote_has("tasks/261017-1400.md"),
        "tasks/<id>.md moves into the intent"
    );
    assert!(home.remote_has("tasks/261099-0000.md"));
    assert_eq!(
        home.remote_file("intents/261020-0721-rust-crate/intent.md"),
        hand
    );
    assert_eq!(
        home.remote_file("done/legacy.md"),
        "2026-10-15 261015-1446 towercab: Rename · towercab#5 · $3.59 · 1m26s · 1\n\
2026-10-15 261015-1715 towercab: Dropped thing · dropped\n"
    );

    let todo = home.remote_file("TODO.md");
    assert!(todo.starts_with("# TODO\n\n<!-- generated by towercab"));
    assert!(todo.contains("- [261016-0403-3](intents/261016-0403-3-publish-early-ci-loop-pip-2-pip-3/intent.md) towercab: Publish early + CI loop (PIP-2, PIP-3) · **review PR** · [towercab#21](https://github.com/MajidBabaeifar/towercab/pull/21)\n"));
    assert!(todo.contains("- [261017-1200](intents/261017-1200-running-one/intent.md) towercab: Running one · **was running before migrate**\n"));
    let done = home.remote_file("DONE.md");
    assert!(done.contains("- 2026-10-17 [261017-1300](done/261017-1300-finished-one/intent.md) pocket-notes: Finished one · no PR · $? · ? · ?\n"));
    assert!(done.ends_with("## Before intents\n\n2026-10-15 261015-1446 towercab: Rename · towercab#5 · $3.59 · 1m26s · 1\n2026-10-15 261015-1715 towercab: Dropped thing · dropped\n"));

    // Writes work now; migrate runs once.
    store.add(new_intent()).unwrap();
    assert_eq!(
        migrate(&store, t("2026-10-21T09:05:00+02:00")).unwrap_err(),
        StoreError::Refused("TODO.md is already generated: migrate has run".into())
    );

    // A generated DONE.md has no old lines to keep.
    assert!(legacy_lines(&done).is_empty());
    assert_eq!(legacy_lines(DONE).len(), 2);

    // `[!]` without a note.
    let t = parse_line("- [!] 261016-0403 towercab: Blocked").unwrap();
    assert_eq!(t.id.as_deref(), Some("261016-0403"));
    assert_eq!(
        towercab::intents::migrate::render(&t, None),
        "---\nrepo: towercab\nsource: me\nwaiting: was [!] before migrate\n---\n\n# Intent: Blocked\n"
    );
}

fn git_parent(home: &Home) -> String {
    common::git(&home.remote, &["rev-parse", "main~1"])
        .trim()
        .to_string()
}

#[test]
fn test_migrate_refuses() {
    let now = t("2026-10-21T09:05:00+02:00");
    // TODO.md missing.
    let home = Home::new(&[]);
    let store = home.store();
    assert_eq!(
        migrate(&store, now).unwrap_err(),
        StoreError::Refused("TODO.md is missing: nothing to migrate".into())
    );
    assert_eq!(home.log(), ["seed"]);

    // Lines that don't parse are all listed; an ID with a folder refuses too; nothing is written.
    let todo = "# TODO
- [?] 261017-1200 towercab: bad marker
- [ ] u3 u4 towercab: twice
- [ ] 261017-1300 no repo here
- [ ] towercab:
- [ ] towercab: fine after:nope
- [ ] 261020-0721 towercab: has a folder
- [ ] 261017-1400 towercab: ok
  not a key line
- [ ] 261017-1400 towercab: same id twice
";
    let home = Home::new(&[
        ("TODO.md", todo),
        ("DONE.md", DONE),
        (
            "intents/261020-0721-x/intent.md",
            &intent_md("towercab", "", "X"),
        ),
    ]);
    let store = home.store();
    let head = home.head();
    let err = migrate(&store, now).unwrap_err();
    assert_eq!(
        err,
        StoreError::Refused(
            "TODO.md:2: not a task line: want `- [ ]`, `[~]`, `[!]` or `[x]` and a title
TODO.md:3: score u given twice
TODO.md:4: expected `<repo>:` after marker, id and scores
TODO.md:5: no title
TODO.md:6: after: needs intent IDs, got nope
TODO.md:7: 261020-0721 already has a folder
TODO.md:9: indented line is not `<key>: <value>`
TODO.md:10: 261017-1400 is on two lines"
                .into()
        )
    );
    assert_eq!(home.head(), head);
    assert!(home.checkout_clean());
    assert!(!home.checkout.join("done").exists());
    assert_eq!(store.scan().open.len(), 1);

    // Already generated.
    let home = Home::new(&[(
        "TODO.md",
        "# TODO\n\n<!-- generated by towercab from intents/*/intent.md: edit those, not this file -->\n\nNothing open.\n",
    )]);
    assert_eq!(
        migrate(&home.store(), now).unwrap_err(),
        StoreError::Refused("TODO.md is already generated: migrate has run".into())
    );
    // done/legacy.md already there.
    let home = Home::new(&[("TODO.md", "# TODO\n"), ("done/legacy.md", "x\n")]);
    assert_eq!(
        migrate(&home.store(), now).unwrap_err(),
        StoreError::Refused("done/legacy.md already exists".into())
    );
}

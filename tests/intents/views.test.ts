// The generated TODO.md and DONE.md (INT-6), in v1's layout.

import { expect, test } from "vitest";
import { agentTime, doneView, isGenerated, prLink, todoView } from "../../src/intents/views.ts";
import { at, listing } from "./fixtures.ts";

const PR21 = "https://github.com/MajidBabaeifar/towercab/pull/21";

test("intents: TODO view", () => {
  const l = listing(
    [
      at("intents/261020-0722-c", "", "towercab", "No scores"),
      at("intents/261019-1000-d", "u: 1\ni: 1\n", "towercab", "Parked low"),
      at("intents/261020-0721-a", "u: 4\ni: 5\na: 5\n", "towercab", "Top"),
      at("intents/261019-0800-older", "u: 4\ni: 5\n", "towercab", "Older top"),
      at(
        "intents/261020-0721-2-b",
        "u: 3\ni: 4\nafter: [261020-0721, 261015-1446, 261014-0900, 261014-1000]\n",
        "towercab",
        "Waits for others",
      ),
      at("intents/261019-1100-e", "u: 2\ni: 2\n", "towercab", "Parked six"),
      at(
        "intents/261018-0900-w",
        `u: 1\ni: 1\nstage: code\nwaiting: review and merge PR\npr: ${PR21}\n`,
        "towercab",
        "Needs me",
      ),
      at(
        "intents/261018-0950-s",
        "stage: spec\nwaiting: approve spec\nspec_pr: https://x/1\n",
        "web",
        "Spec",
      ),
      at("intents/261018-1000-f", "stage: build\n", "towercab", "Building"),
      at(
        "intents/261018-1100-g",
        "u: 5\ni: 5\nstage: plan\npr: https://example.com/x\n",
        "towercab",
        "Planning",
      ),
      at("done/261014-0900-old", "stage: done\n", "towercab", "Old"),
      at("done/261014-1000-gone", "stage: dropped\n", "towercab", "Gone"),
    ],
    "2026-10-15 261015-1446 towercab: Rename · towercab#5 · $3.59 · 1m26s · 1\n",
    [
      { path: "intents/zzz", reason: "not an <id>-<slug> folder", id: null },
      { path: "intents/261017-0000-x/intent.md", reason: "u must be an integer 1-5", id: "261017-0000" },
    ],
  );
  const want = `# TODO

<!-- generated by towercab from intents/*/intent.md: edit those, not this file -->

## Waiting on me

- [261018-0950](intents/261018-0950-s/intent.md) web: Spec · **approve spec** · https://x/1
- [261018-0900](intents/261018-0900-w/intent.md) towercab: Needs me · **review and merge PR** · [towercab#21](https://github.com/MajidBabaeifar/towercab/pull/21)

## In flight

- [261018-1100](intents/261018-1100-g/intent.md) towercab: Planning · plan · https://example.com/x
- [261018-1000](intents/261018-1000-f/intent.md) towercab: Building · code

## Next

- [261019-0800](intents/261019-0800-older/intent.md) towercab: Older top · p14 u4 i5
- [261020-0721](intents/261020-0721-a/intent.md) towercab: Top · p14 u4 i5 a5
- [261020-0721-2](intents/261020-0721-2-b/intent.md) towercab: Waits for others · p11 u3 i4 · after 261020-0721, 261014-1000
- [261020-0722](intents/261020-0722-c/intent.md) towercab: No scores · p9 u3 i3

## Parked

- [261019-1100](intents/261019-1100-e/intent.md) towercab: Parked six · p6 u2 i2
- [261019-1000](intents/261019-1000-d/intent.md) towercab: Parked low · p3 u1 i1

## Can't read

- intents/261017-0000-x/intent.md: u must be an integer 1-5
- intents/zzz: not an <id>-<slug> folder
`;
  expect(todoView(l, 7)).toBe(want);
  expect(isGenerated(want)).toBe(true);
  expect(todoView(l, 4)).toContain(
    "## Parked\n\n- [261019-1000](intents/261019-1000-d/intent.md) towercab: Parked low · p3 u1 i1\n\n## Can't read",
  );
  expect(todoView(listing([]), 7)).toBe(
    "# TODO\n\n<!-- generated by towercab from intents/*/intent.md: edit those, not this file -->\n\nNothing open.\n",
  );
  // Values on one line: a line break can't start a heading or an entry.
  const multi = listing(
    [
      at(
        "intents/261020-0721-a",
        'waiting: "line one\\n## Injected\\n- [x] fake"\npr: "https://x\\n# y"\n',
        "towercab",
        "Multi",
      ),
    ],
    "",
    [{ path: "intents/a\nb", reason: "two\nlines", id: null }],
  );
  expect(todoView(multi, 7)).toMatch(
    /## Waiting on me\n\n- \[261020-0721\]\(intents\/261020-0721-a\/intent\.md\) towercab: Multi · \*\*line one ## Injected - \[x\] fake\*\* · https:\/\/x # y\n\n## Can't read\n\n- intents\/a b: two lines\n$/,
  );
  expect(isGenerated("# TODO\n\n- [ ] 261020-0721 towercab: old line\n")).toBe(false);
});

test("intents: DONE view", () => {
  expect([agentTime(86), agentTime(5), agentTime(3599), agentTime(3700)]).toEqual([
    "1m26s",
    "0m05s",
    "59m59s",
    "1h01m",
  ]);
  expect(prLink(PR21)).toBe(`[towercab#21](${PR21})`);
  expect(prLink("https://example.com/7")).toBe("https://example.com/7");
  const l = listing([
    at("done/261015-0900-z", "", "towercab", "Moved by hand"),
    at(
      "done/261016-0403-3-x",
      `stage: done\npr: ${PR21}\ncost: 3.5\nagent_time: 86\nattempts: 1\nfinished: 2026-10-18T09:00:00+02:00\n`,
      "towercab",
      "Publish early",
    ),
    at(
      "done/261017-0900-y",
      "stage: dropped\nfinished: 2026-10-18T08:00:00+02:00\n",
      "towercab",
      "Not needed",
    ),
    at(
      "intents/261017-1000-h",
      `stage: dropped\npr: ${PR21}\nfinished: 2026-10-18T23:30:00-05:00\n`,
      "towercab",
      "Dropped in place",
    ),
    at(
      "done/261016-1000-long",
      "stage: done\nagent_time: 3700\ncost: 12\nattempts: 3\n",
      "towercab",
      "Long one",
    ),
  ]);
  const legacy =
    "2026-10-15 261015-1446 towercab: Rename · towercab#5 · $3.59 · 1m26s · 1\n" +
    "2026-10-15 261015-1715 towercab: Dropped thing · dropped\n\n";
  const want = `# DONE

<!-- generated by towercab from done/*/intent.md and done/legacy.md: edit those, not this file -->

- 2026-10-18 [261017-1000](intents/261017-1000-h/intent.md) towercab: Dropped in place · dropped · [towercab#21](https://github.com/MajidBabaeifar/towercab/pull/21)
- 2026-10-18 [261017-0900](done/261017-0900-y/intent.md) towercab: Not needed · dropped
- 2026-10-18 [261016-0403-3](done/261016-0403-3-x/intent.md) towercab: Publish early · [towercab#21](https://github.com/MajidBabaeifar/towercab/pull/21) · $3.50 · 1m26s · 1
- 2026-10-16 [261016-1000](done/261016-1000-long/intent.md) towercab: Long one · no PR · $12.00 · 1h01m · 3
- 2026-10-15 [261015-0900](done/261015-0900-z/intent.md) towercab: Moved by hand · no PR · $? · ? · ?

## Before intents

2026-10-15 261015-1446 towercab: Rename · towercab#5 · $3.59 · 1m26s · 1
2026-10-15 261015-1715 towercab: Dropped thing · dropped
`;
  expect(doneView(l, legacy)).toBe(want);
  expect(isGenerated(want)).toBe(true);
  expect(doneView(listing([]), "")).toBe(
    "# DONE\n\n<!-- generated by towercab from done/*/intent.md and done/legacy.md: edit those, not this file -->\n\nNothing done.\n",
  );
  expect(doneView(listing([]), "2026-10-15 261015-1446 towercab: Rename\n")).toMatch(
    /-->\n\n## Before intents\n\n2026-10-15 261015-1446 towercab: Rename\n$/,
  );
});
